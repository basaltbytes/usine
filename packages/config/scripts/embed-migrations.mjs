import { readdir, readFile, writeFile } from "node:fs/promises";

const directories = (await readdir("drizzle", { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const migrations = await Promise.all(
  directories.map(async (directory, index) => [
    `${index + 1}_${directory}`,
    (await readFile(`drizzle/${directory}/migration.sql`, "utf8"))
      .split("--> statement-breakpoint")
      .map((sql) => sql.trim())
      .filter(Boolean),
  ]),
);
await writeFile(
  "src/configuration/sqlite/migrations.ts",
  `// Generated by scripts/embed-migrations.mjs from the Drizzle migrations.\nexport const migrations = ${JSON.stringify(migrations, null, 2)} as const;\n`,
);
