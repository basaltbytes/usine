import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { Schema } from "effect";
import { format } from "oxfmt";
import { CODEX_PROTOCOL } from "../../src/protocol/codex/version.ts";
import { emitDeclarations } from "./emit.mjs";

const output = new URL("../../src/protocol/codex/generated.ts", import.meta.url);
const copyPath = "src/protocol/codex/upstream-schema.json";
const copy = new URL(`../../${copyPath}`, import.meta.url);
const formatterConfig = new URL("../../../../.oxfmtrc.json", import.meta.url);
const source = `https://raw.githubusercontent.com/openai/codex/${CODEX_PROTOCOL.commit}/codex-rs/app-server-protocol/schema/json/codex_app_server_protocol.schemas.json`;
const roots = [
  "ThreadResumeResponse",
  "ThreadStartResponse",
  "TurnStartResponse",
  "TurnCompletedNotification",
  "ItemStartedNotification",
  "ItemCompletedNotification",
  "ThreadTokenUsageUpdatedNotification",
  "AccountRateLimitsUpdatedNotification",
  "AccountUpdatedNotification",
  "ErrorNotification",
  "ModelListResponse",
  "GetAccountResponse",
  "AgentMessageDeltaNotification",
];
const UPSTREAM_UNAVAILABLE = 2;
const check = process.argv.includes("--check");
const upstream = process.argv.includes("--upstream");

/**
 * Returns the pinned upstream schema text. If the request or the response fails, prints one line
 * that ends with `consequence` and exits with `UPSTREAM_UNAVAILABLE`.
 */
const fetchUpstream = async (consequence) => {
  let reason;
  try {
    const response = await fetch(source, { signal: AbortSignal.timeout(60_000) });
    if (response.ok) return await response.text();
    reason = `HTTP ${response.status} ${response.statusText}`.trim();
  } catch (error) {
    const cause = error instanceof Error ? error.cause : undefined;
    reason =
      (cause instanceof Error && (cause.message || cause.code)) ||
      (error instanceof Error ? error.message || error.name : `${error}`);
  }
  console.error(`upstream fetch failed: ${reason}; ${consequence}`);
  process.exit(UPSTREAM_UNAVAILABLE);
};

const text =
  upstream && !check ? await fetchUpstream("nothing was written") : await readFile(copy, "utf8");
const document = Schema.decodeUnknownSync(
  Schema.fromJsonString(
    Schema.Struct({
      $schema: Schema.Literal("http://json-schema.org/draft-07/schema#"),
      definitions: Schema.Struct({ v2: Schema.Record(Schema.String, Schema.Json) }),
    }),
  ),
)(text);

const header = `// Generated by scripts/codex/generate.mjs. Do not edit.\n// Source: ./upstream-schema.json, the openai/codex schema at the commit in ./version.ts.\n// String enums are open; single-value enums, which tag union variants, remain literals.\nimport { Schema } from "effect";\n\n`;
const code =
  header +
  [...emitDeclarations(document.definitions.v2, roots)]
    .map(([name, expression]) => `export const ${name} = ${expression};\n`)
    .join("\n");
const formatted = await format(
  "generated.ts",
  code,
  JSON.parse(await readFile(formatterConfig, "utf8")),
);
assert.equal(formatted.errors.length, 0, JSON.stringify(formatted.errors));
if (check) {
  assert(
    (await readFile(output, "utf8")) === formatted.code,
    "Codex schemas are stale. Run pnpm --filter @usine/agents codex:generate",
  );
  if (upstream) {
    assert(
      (await fetchUpstream("the local copy was checked")) === text,
      `${copyPath} does not match ${source}. Run pnpm --filter @usine/agents codex:update`,
    );
  }
} else {
  if (upstream) await writeFile(copy, text);
  await writeFile(output, formatted.code);
}
